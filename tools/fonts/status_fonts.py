"""Small tabular Inter figures and a Framework7 bolt for live battery indicators.

These tiny subsets always live in the app, including accessibility sizes, so drawing
a battery never needs a flash read. Their public selector follows orb_fonts settings.
"""

from pathlib import Path

from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont

import icons
import inter
import spec

DIGITS = [0x20, *range(ord("0"), ord("9") + 1)]
BOLT = 0xE153


def size_for_px(px: int) -> int:
    return max(10, (px * 44 + 50) // 100)


def extend_plan(font_type, fonts: dict, sets: list) -> None:
    for fs in sets:
        for row in fs.styles:
            px = size_for_px(row["style"].px)
            for weight in (600, 700):
                name = f"orb_status_{px}_{spec.WEIGHT_NAMES[weight]}"
                fonts.setdefault(
                    name,
                    font_type(name, "status", px, weight, 14, [*DIGITS, BOLT], home="app"),
                )


def make_ttf(f, variable: Path, assets: Path, out: Path) -> dict:
    font = inter.instance(variable, f.weight, f.opsz)
    frozen = inter.frozen_glyphs(
        variable, f.weight, f.opsz, {cp: "0" + chr(cp) + "0" for cp in DIGITS}, {"tnum": True}
    )
    inter.remap_cmap(font, frozen)
    cap = font["OS/2"].sCapHeight
    scale = icons.icon_scale(cap, spec.ICON_CIRCLE_CAP_HEIGHTS)
    stroke = spec.ICON_STROKE_RATIO * inter.stem_em(font) * icons.UPM / scale
    inter.subset_to(font, DIGITS)

    # Build both states so the normal fill/outline placement checks apply; only the
    # filled bolt is copied into this font. No whole icon font is retained.
    bolt_path = out.with_suffix(".bolt.ttf")
    glyphs = [g for g in spec.icon_codepoints() if g[0] in ("LIGHTNING", "LIGHTNING_FILL")]
    icons.build(
        assets,
        glyphs,
        spec.icon_groups(),
        stroke,
        scale,
        cap / 2,
        0,
        font["hhea"].ascent,
        font["hhea"].descent,
        font["hmtx"][font.getBestCmap()[0x20]][0],
        f"Orb Battery Bolt {f.px}",
        f.px,
        bolt_path,
    )
    with TTFont(bolt_path) as bolt:
        name = bolt.getBestCmap()[BOLT]
        glyph = bolt["glyf"][name]
        # A normal symbol deliberately overshoots capitals; a battery bolt must
        # fit inside the inset body at even Footnote2 and AX3 Bold Text. Preserve
        # its aspect ratio, make it 1.1 digit cap heights and centre beside digits.
        ratio = cap * 1.1 / (glyph.yMax - glyph.yMin)
        shift_y = cap / 2 - (glyph.yMin + glyph.yMax) / 2 * ratio
        pen = TTGlyphPen(None)
        bolt.getGlyphSet()[name].draw(TransformPen(pen, (ratio, 0, 0, ratio, 0, shift_y)))
        font["glyf"][name] = pen.glyph()
        advance, bearing = bolt["hmtx"][name]
        font["hmtx"][name] = (round(advance * ratio), round(bearing * ratio))
        for table in font["cmap"].tables:
            if table.isUnicode():
                table.cmap[BOLT] = name
    bolt_path.unlink()
    inter.rename(font, f"Orb Battery {f.px}", spec.WEIGHT_NAMES[f.weight].title())
    font.save(out)
    return {"status": {"tabular": True, "bolt": "Framework7 bolt_fill"}}


def emit_selector(path: Path, fonts: dict, sets: list) -> None:
    sizes = sorted({f.px for f in fonts.values() if f.kind == "status"}, reverse=True)
    out = [
        "/* Generated by tools/fonts/status_fonts.py. Do not edit. */",
        '#include "orb_fonts.h"',
        "",
    ]
    out += [f"LV_FONT_DECLARE({n})" for n, f in sorted(fonts.items()) if f.kind == "status"]
    out += [
        "",
        "/* Public selection adds the app-owned ellipsis fallback without changing these",
        " * generated numeric glyphs or the signed font pack. */",
        "const lv_font_t *orb_status_builtin_font_for_cap(orb_text_style_t style,",
        "                                        orb_text_variant_t variant, int32_t cap_height)",
        "{",
        "    const orb_text_style_info_t *info = orb_text_style_info(style);",
        "    const unsigned weight = (variant & ORB_TEXT_EMPHASIZED) ?",
        "                            info->emphasized_weight : info->weight;",
        "    unsigned px = (info->size_px * 44u + 50u) / 100u;",
        "    /* Use the widget's measured cap, even if a failed pack load recovers",
        "     * between layout and drawing. This selector never reads the pack. */",
        "    if (cap_height > 0) {",
        "        unsigned limit = ((unsigned)cap_height * 3u + 2u) / 5u;",
        "        if (px > limit) px = limit;",
        "    }",
    ]
    for px in sizes:
        out.append(
            f"    if (px >= {px}) return weight >= 600 ? &orb_status_{px}_bold : "
            f"&orb_status_{px}_semibold;"
        )
    out += [
        "    return weight >= 600 ? &orb_status_10_bold : &orb_status_10_semibold;",
        "}",
        "",
        "const lv_font_t *orb_status_font(orb_text_style_t style, orb_text_variant_t variant)",
        "{",
        "    lv_font_glyph_dsc_t cap;",
        "    int32_t height = lv_font_get_glyph_dsc(orb_font_variant(style, variant),",
        "                                           &cap, 'H', 0) ? (int32_t)cap.box_h : 0;",
        "    return orb_status_font_for_cap(style, variant, height);",
        "}",
        "",
    ]
    path.write_text("\n".join(out))
