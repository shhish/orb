"""Writes the generated C tables, the notices, the icon header and the README size tables."""

import re
from pathlib import Path

import spec

GENERATED = "Generated by tools/fonts/build.py (scripts/fonts.sh). Do not edit."


def _utf8_literal(cp: int) -> str:
    return '"' + "".join(f"\\x{b:02X}" for b in chr(cp).encode()) + '"'


def icons_header(path: Path) -> None:
    glyphs = spec.icon_codepoints()
    width = max(len(m) for m, _, _, _ in glyphs) + len("ORB_ICON_")
    lines = [
        "#pragma once",
        "",
        "/*",
        " * Orb's icons: UTF-8 strings in the Unicode private use area. Every Orb text font",
        " * falls back to the icon font of the same size and weight, so icons can sit inline:",
        ' *     lv_label_set_text(label, ORB_ICON_MIC " Listening");',
        " * Icons-only labels use orb_icon_font(), whose line box is centred on the icons.",
        " * ORB_ICON_<NAME>_FILL is the filled form, at the outline's codepoint + 0x100; it",
        " * shares its outline's bounds and advance at every weight, so they swap in place.",
        f" * Codepoints are stable. {GENERATED}",
        " * Artwork: Framework7 Icons 5.0.5; explicit Phosphor 2.1.1 fallbacks (MIT, licenses/).",
        " * Battery/Wi-Fi macros remain compatible; use orb_status for live status indicators.",
        " */",
        "",
    ]
    for macro, cp, asset, is_fill in glyphs:
        name = f"ORB_ICON_{macro}"
        src = spec.icon_asset(asset, macro, is_fill)
        if src.startswith("phosphor:") and is_fill:
            src += " (fill)"
        lines.append(f"#define {name:<{width}} {_utf8_literal(cp)} /* U+{cp:04X} {src} */")
    lines += [
        "",
        f"#define ORB_ICONS_COUNT {len(glyphs)}",
        "",
        "/* X(NAME, codepoint) for every icon, e.g. for a gallery. */",
    ]
    lines.append("#define ORB_ICONS_FOREACH(X) \\")
    for i, (macro, cp, _, _) in enumerate(glyphs):
        cont = " \\" if i < len(glyphs) - 1 else ""
        lines.append(f"    X({macro}, 0x{cp:04X}){cont}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def _check_enum(header: str, typedef: str, prefix: str, names: list[str]) -> None:
    """The generated tables index the hand-written enums: their orders must agree."""
    body = re.search(r"typedef enum \{(.*?)\}\s*" + typedef + ";", header, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    found = [n for n in re.findall(rf"\b{prefix}([A-Z0-9_]+)", body) if not n.endswith("COUNT")]
    assert found == names, f"{typedef} in orb_fonts.h is {found}, tools/fonts/spec.py has {names}"


def font_table(
    path: Path,
    fonts: dict,
    sets: list,
    ids: dict[str, int],
    pack_names: list[str],
    entries: list[dict],
    pack_id: bytes,
    pack_size: int,
) -> None:
    header = (path.parent.parent / "include" / "orb_fonts.h").read_text()
    _check_enum(header, "orb_text_style_t", "ORB_TEXT_", [s.enum for s in spec.STYLES])
    _check_enum(header, "orb_clock_t", "ORB_CLOCK_", [c.enum for c in spec.CLOCK_FACES])
    _check_enum(
        header, "orb_content_size_t", "ORB_CONTENT_SIZE_", [c.enum for c in spec.CONTENT_SIZES]
    )

    app = sorted((n for n, f in fonts.items() if f.home == "app"), key=ids.get)
    assert [ids[n] for n in app] == list(range(len(app)))
    assert [ids[n] for n in pack_names] == list(range(len(app), len(app) + len(pack_names)))
    out = [
        f"/* {GENERATED} */",
        "",
        '#include "orb_fonts_private.h"',
        "",
    ]
    out += [f"LV_FONT_DECLARE({name})" for name in app]
    out += [
        "",
        "/* Font ids 0.. : fonts in the app image. */",
        "static const lv_font_t *const builtin[] = {",
    ]
    out += [f"    &{n}, /* {ids[n]} */" for n in app]
    out += ["};", ""]
    out += [
        f"/* Font ids {len(app)}.. : records in the font pack ({len(pack_names)} fonts, {pack_size} bytes). */",
        "static const orb_pack_entry_t pack_entries[] = {",
    ]
    for n, e in zip(pack_names, entries, strict=True):
        out.append(f"    {{{e['offset']}, {e['stored']}, {e['size']}}}, /* {ids[n]} {n} */")
    out += ["};", ""]
    out += ["const orb_fonts_table_t orb_fonts_table = {"]
    out += ["    .notices = orb_fonts_notices_text,"]
    out += ["    .style_names = {"]
    out += [f'        [ORB_TEXT_{s.enum}] = "{s.name}",' for s in spec.STYLES]
    out += ["    },", "    .clock_faces = {"]
    for c, row in zip(spec.CLOCK_FACES, sets[0].clocks, strict=True):
        out.append(
            f"        [ORB_CLOCK_{c.enum}] = {{{c.px}, {c.tracking}, {row['letter_space']}}},"
        )
    out += ["    },", "    .sets = {"]
    for size in spec.CONTENT_SIZES:
        out.append(f"        [ORB_CONTENT_SIZE_{size.enum}] = {{")
        for fs in (s for s in sets if s.size is size):
            out.append(f"            [{int(fs.bold)}] = {{ /* {fs.title} */")
            out.append("                .styles = {")
            for r in fs.styles:
                s = r["style"]
                reg, emph = r["regular"], r["emphasized"]
                face = "{{{}, {}, {}}}"
                faces = ", ".join(
                    face.format(ids[v["text"]], ids[v["tnum"]], ids[v["icons"]])
                    for v in (reg, emph)
                )
                out.append(
                    f"                    [ORB_TEXT_{s.enum}] = {{{int(s.pt)}, {s.px}, {s.leading_px}, "
                    f"{r['letter_space']}, {s.tracking}, {{{reg['weight']}, {emph['weight']}}}, {{{faces}}}}},"
                    f" /* {reg['text']}, {emph['text']} */"
                )
            out.append("                },")
            clocks = ", ".join(f"{{{ids[c['font']]}, {c['clock'].weight}}}" for c in fs.clocks)
            out.append(f"                .clocks = {{{clocks}}},")
            out.append("            },")
        out.append("        },")
    out += ["    },"]
    out += ["    .builtin = builtin,", f"    .builtin_count = {len(app)},"]
    out += ["    .pack = pack_entries,", f"    .pack_count = {len(pack_names)},"]
    out += [f"    .pack_size = {pack_size},"]
    out += ["    .pack_id = {" + ", ".join(f"0x{b:02X}" for b in pack_id) + "},"]
    out += ["};", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out))


def notices(path: Path, text: str) -> None:
    """The licences, compiled into the image (the table references them, so whatever links
    a font links them)."""
    lines = [
        f"/* {GENERATED} */",
        "",
        '#include "orb_fonts_private.h"',
        "",
        "/* Inter's and Phosphor's licences require their notices in every copy; this is it. */",
        "const char orb_fonts_notices_text[] =",
    ]
    for line in text.splitlines():
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{esc}\\n"')
    lines[-1] += ";"
    path.write_text("\n".join(lines) + "\n")


def _kb(n: int) -> str:
    return f"{n / 1024:.1f}"


def readme_sizes(path: Path, fonts: dict, sets: list, pack_size: int) -> None:
    uses: dict[str, list[str]] = {}
    for fs in sets:
        for r in fs.styles:
            for variant in ("regular", "emphasized"):
                for kind in ("text", "tnum", "icons"):
                    label = r["style"].name + (" emphasized" if variant == "emphasized" else "")
                    if fs.size.enum != "DEFAULT" or fs.bold:
                        label += f" ({fs.title})"
                    uses.setdefault(r[variant][kind], []).append(label)
        for c in fs.clocks:
            uses.setdefault(c["font"], []).append(
                f"Clock {c['clock'].enum.lower()}" + (" (Bold Text)" if fs.bold else "")
            )

    def table(names: list[str], pack: bool) -> list[str]:
        rows = [
            "| Font | Used by | px | opsz | Glyphs | Bitmaps (KiB) | Total (KiB) | Stored |"
            + (" In pack (KiB) |" if pack else ""),
            "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |" + (" ---: |" if pack else ""),
        ]
        for name in sorted(names, key=lambda n: (fonts[n].kind, -fonts[n].px, n)):
            f = fonts[name]
            c = f.info["c"]
            used = ["Live battery digits + bolt"] if f.kind == "status" else uses.get(name, [])
            use = ", ".join(dict.fromkeys(used[:3])) + (
                f" and {len(used) - 3} more" if len(used) > 3 else ""
            )
            stored = "RLE" if c["bitmap_format"] else "plain"
            row = (
                f"| `{name}` | {use} | {f.px} | {f.opsz} | {c['glyph_count']} | {_kb(c['bitmap_bytes'])} | "
                f"{_kb(c['total_bytes'])} | {stored} |"
            )
            if pack:
                row += f" {_kb(f.info['pack']['stored'])} |"
            rows.append(row)
        return rows

    kinds = {
        "text": "Text",
        "tnum": "Tabular figures",
        "icons": "Icons",
        "clock": "Clock",
        "status": "Battery figures and bolt",
    }
    app = [n for n, f in fonts.items() if f.home == "app"]
    totals: dict[str, int] = {}
    for n in app:
        totals[fonts[n].kind] = totals.get(fonts[n].kind, 0) + fonts[n].info["c"]["total_bytes"]
    rows = ["**In the app image** (28 px rescue text/icons plus compact battery markings):", ""]
    rows += table(app, False)
    summary = ", ".join(
        f"{kinds[k]} {_kb(v)} KiB" for k, v in sorted(totals.items(), key=lambda kv: -kv[1])
    )
    rows += [
        "",
        f"**{len(app)} fonts, {_kb(sum(totals.values()))} KiB** of font data ({summary}).",
        "",
    ]

    packed = [n for n, f in fonts.items() if f.home == "pack"]
    loaded = sum(fonts[n].info["c"]["total_bytes"] for n in packed)
    rows += [
        f"**In the font pack** (`pack/orb_fonts.pack`): {len(packed)} fonts, "
        f"{_kb(pack_size)} KiB in flash ({_kb(loaded)} KiB of font data, zlib-compressed). "
        "A set's fonts come from the app where they are the same font (same size, weight and "
        "optical size) and from the pack otherwise. The generated font data below excludes "
        "record layout and converted LVGL metadata (see Loading above for actual buffer bytes):",
        "",
        "| Set | Body | Fonts | From the app | From the pack | Generated font data (KiB) |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for fs in sets:
        names = fs.font_names()
        mine = [n for n in names if fonts[n].home == "pack"]
        body = next(r["style"] for r in fs.styles if r["style"].enum == "BODY")
        rows.append(
            f"| {fs.title} | {body.px} px | {len(names)} | {len(names) - len(mine)} | {len(mine)} | "
            f"{_kb(sum(fonts[n].info['c']['total_bytes'] for n in mine))} |"
        )
    rows += ["", "<details><summary>Every font in the pack</summary>", ""]
    rows += table(packed, True)
    rows += ["", "</details>"]

    _replace_block(path, "sizes", "\n".join(rows))


def _replace_block(path: Path, name: str, block: str) -> None:
    text = path.read_text() if path.exists() else ""
    begin, end = f"<!-- {name}:begin -->", f"<!-- {name}:end -->"
    if begin not in text:
        print(f"note: {path} has no {begin} marker; {name} not written")
        return
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    path.write_text(f"{head}{begin}\n{block}\n{end}{tail}")


def readme_styles(path: Path, sets: list) -> None:
    """The text style table: every style at each content size, with Bold Text's weights."""
    weight = {w: n.title() for w, n in spec.WEIGHT_NAMES.items()}
    weight[800] = "Heavy"  # Inter calls 800 ExtraBold
    plain = {fs.size.enum: fs for fs in sets if not fs.bold}
    bold = {fs.size.enum: fs for fs in sets if fs.bold}
    head = "| Style | Weight | Emphasized | " + " | ".join(
        f"{c.name} ({c.apple})" if c.apple != c.name else c.name for c in spec.CONTENT_SIZES
    )
    rows = [
        head + " |",
        "| --- | --- | --- |" + " ---: |" * len(spec.CONTENT_SIZES),
    ]
    for i, st in enumerate(spec.STYLES):
        b = bold["DEFAULT"].styles[i]["style"]
        cells = [
            st.name,
            f"{weight[st.weight]} ({weight[b.weight]})",
            f"{weight[st.emphasized_weight]} ({weight[b.emphasized_weight]})",
        ]
        for c in spec.CONTENT_SIZES:
            s = plain[c.enum].styles[i]["style"]
            cells.append(
                f"{s.px} / {s.leading_px} px · {s.tracking:+d}".replace("+0", "0").replace("-", "−")
            )
        rows.append("| " + " | ".join(cells) + " |")
    rows += [
        "",
        "Each size cell is px / leading, then Apple's tracking (1/1000 em) for that point size. "
        "Weights in brackets are with Bold Text.",
    ]
    _replace_block(path, "styles", "\n".join(rows))


def coverage_header(path: Path) -> None:
    """Character sets for the self-test (test_app), so it checks exactly what was generated."""

    def array(name: str, cps: list[int]) -> list[str]:
        out = [f"static const uint32_t {name}[] = {{"]
        for i in range(0, len(cps), 10):
            out.append("    " + " ".join(f"0x{cp:04X}," for cp in cps[i:][:10]))
        return out + ["};", ""]

    lines = ["#pragma once", "", f"/* {GENERATED} */", "", "#include <stdint.h>", ""]
    lines += array("orb_test_text_codepoints", spec.TEXT_CODEPOINTS)
    lines += array("orb_test_tabular_codepoints", spec.TABULAR_CODEPOINTS)
    lines += array("orb_test_clock_codepoints", spec.CLOCK_CODEPOINTS)
    path.write_text("\n".join(lines))
